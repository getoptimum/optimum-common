//go:build !purego

#include "textflag.h"

// Each byte b is split into its low and high nibble. TBL looks both up in the
// factor's 16-byte tables, and the two products are XORed, since f·b is
// f·(b & 15) XOR f·(b & 240).
//
// V0 holds the low-nibble table, V1 the high-nibble table and V2 the 0x0f mask.

// func neonMul(tables *[32]byte, dst, src []byte)
TEXT ·neonMul(SB), NOSPLIT, $0-56
	MOVD tables+0(FP), R0
	MOVD dst_base+8(FP), R1
	MOVD dst_len+16(FP), R2
	MOVD src_base+32(FP), R3
	VLD1 (R0), [V0.B16, V1.B16]
	VMOVI $15, V2.B16
	CMP  $64, R2
	BLT  mul32

mul64:
	VLD1.P 64(R3), [V4.B16, V5.B16, V6.B16, V7.B16]
	VAND   V2.B16, V4.B16, V16.B16
	VAND   V2.B16, V5.B16, V17.B16
	VAND   V2.B16, V6.B16, V18.B16
	VAND   V2.B16, V7.B16, V19.B16
	VUSHR  $4, V4.B16, V4.B16
	VUSHR  $4, V5.B16, V5.B16
	VUSHR  $4, V6.B16, V6.B16
	VUSHR  $4, V7.B16, V7.B16
	VTBL   V16.B16, [V0.B16], V16.B16
	VTBL   V17.B16, [V0.B16], V17.B16
	VTBL   V18.B16, [V0.B16], V18.B16
	VTBL   V19.B16, [V0.B16], V19.B16
	VTBL   V4.B16, [V1.B16], V4.B16
	VTBL   V5.B16, [V1.B16], V5.B16
	VTBL   V6.B16, [V1.B16], V6.B16
	VTBL   V7.B16, [V1.B16], V7.B16
	VEOR   V4.B16, V16.B16, V16.B16
	VEOR   V5.B16, V17.B16, V17.B16
	VEOR   V6.B16, V18.B16, V18.B16
	VEOR   V7.B16, V19.B16, V19.B16
	VST1.P [V16.B16, V17.B16, V18.B16, V19.B16], 64(R1)
	SUB    $64, R2, R2
	CMP    $64, R2
	BGE    mul64

mul32:
	CMP    $32, R2
	BLT    mul16
	VLD1.P 32(R3), [V4.B16, V5.B16]
	VAND   V2.B16, V4.B16, V16.B16
	VAND   V2.B16, V5.B16, V17.B16
	VUSHR  $4, V4.B16, V4.B16
	VUSHR  $4, V5.B16, V5.B16
	VTBL   V16.B16, [V0.B16], V16.B16
	VTBL   V17.B16, [V0.B16], V17.B16
	VTBL   V4.B16, [V1.B16], V4.B16
	VTBL   V5.B16, [V1.B16], V5.B16
	VEOR   V4.B16, V16.B16, V16.B16
	VEOR   V5.B16, V17.B16, V17.B16
	VST1.P [V16.B16, V17.B16], 32(R1)
	SUB    $32, R2, R2

mul16:
	CBZ   R2, mulDone
	VLD1  (R3), [V4.B16]
	VAND  V2.B16, V4.B16, V16.B16
	VUSHR $4, V4.B16, V4.B16
	VTBL  V16.B16, [V0.B16], V16.B16
	VTBL  V4.B16, [V1.B16], V4.B16
	VEOR  V4.B16, V16.B16, V16.B16
	VST1  [V16.B16], (R1)

mulDone:
	RET

// func neonXor(tables *[32]byte, dst, src []byte)
TEXT ·neonXor(SB), NOSPLIT, $0-56
	MOVD tables+0(FP), R0
	MOVD dst_base+8(FP), R1
	MOVD dst_len+16(FP), R2
	MOVD src_base+32(FP), R3
	VLD1 (R0), [V0.B16, V1.B16]
	VMOVI $15, V2.B16
	CMP  $64, R2
	BLT  xor32

xor64:
	VLD1.P 64(R3), [V4.B16, V5.B16, V6.B16, V7.B16]
	VLD1   (R1), [V20.B16, V21.B16, V22.B16, V23.B16]
	VAND   V2.B16, V4.B16, V16.B16
	VAND   V2.B16, V5.B16, V17.B16
	VAND   V2.B16, V6.B16, V18.B16
	VAND   V2.B16, V7.B16, V19.B16
	VUSHR  $4, V4.B16, V4.B16
	VUSHR  $4, V5.B16, V5.B16
	VUSHR  $4, V6.B16, V6.B16
	VUSHR  $4, V7.B16, V7.B16
	VTBL   V16.B16, [V0.B16], V16.B16
	VTBL   V17.B16, [V0.B16], V17.B16
	VTBL   V18.B16, [V0.B16], V18.B16
	VTBL   V19.B16, [V0.B16], V19.B16
	VTBL   V4.B16, [V1.B16], V4.B16
	VTBL   V5.B16, [V1.B16], V5.B16
	VTBL   V6.B16, [V1.B16], V6.B16
	VTBL   V7.B16, [V1.B16], V7.B16
	VEOR   V4.B16, V16.B16, V16.B16
	VEOR   V5.B16, V17.B16, V17.B16
	VEOR   V6.B16, V18.B16, V18.B16
	VEOR   V7.B16, V19.B16, V19.B16
	VEOR   V20.B16, V16.B16, V16.B16
	VEOR   V21.B16, V17.B16, V17.B16
	VEOR   V22.B16, V18.B16, V18.B16
	VEOR   V23.B16, V19.B16, V19.B16
	VST1.P [V16.B16, V17.B16, V18.B16, V19.B16], 64(R1)
	SUB    $64, R2, R2
	CMP    $64, R2
	BGE    xor64

xor32:
	CMP    $32, R2
	BLT    xor16
	VLD1.P 32(R3), [V4.B16, V5.B16]
	VLD1   (R1), [V20.B16, V21.B16]
	VAND   V2.B16, V4.B16, V16.B16
	VAND   V2.B16, V5.B16, V17.B16
	VUSHR  $4, V4.B16, V4.B16
	VUSHR  $4, V5.B16, V5.B16
	VTBL   V16.B16, [V0.B16], V16.B16
	VTBL   V17.B16, [V0.B16], V17.B16
	VTBL   V4.B16, [V1.B16], V4.B16
	VTBL   V5.B16, [V1.B16], V5.B16
	VEOR   V4.B16, V16.B16, V16.B16
	VEOR   V5.B16, V17.B16, V17.B16
	VEOR   V20.B16, V16.B16, V16.B16
	VEOR   V21.B16, V17.B16, V17.B16
	VST1.P [V16.B16, V17.B16], 32(R1)
	SUB    $32, R2, R2

xor16:
	CBZ   R2, xorDone
	VLD1  (R3), [V4.B16]
	VLD1  (R1), [V20.B16]
	VAND  V2.B16, V4.B16, V16.B16
	VUSHR $4, V4.B16, V4.B16
	VTBL  V16.B16, [V0.B16], V16.B16
	VTBL  V4.B16, [V1.B16], V4.B16
	VEOR  V4.B16, V16.B16, V16.B16
	VEOR  V20.B16, V16.B16, V16.B16
	VST1  [V16.B16], (R1)

xorDone:
	RET
